import assert from "node:assert/strict";
import {test} from "node:test";
import {
    formatActivationCode,
    isActivationCodeComplete,
    isDeviceCredentialFault,
    isOperatorSessionFault,
    normalizeActivationCode,
    parseActivationQr,
} from "./activation.ts";

test("parses the QR payload generated by the manager panel", () => {
    const raw = JSON.stringify({
        type: "MANAGER_DEVICE_ACTIVATION",
        serverUrl: " https://manager.example.com/v1/api ",
        activationCode: "abcdefgh",
    });

    assert.deepEqual(parseActivationQr(raw), {
        serverUrl: "https://manager.example.com/v1/api",
        activationCode: "ABCD-EFGH",
    });
});

test("rejects QR codes that are not activation payloads", () => {
    assert.equal(parseActivationQr("TRACK123"), null);
    assert.equal(parseActivationQr(JSON.stringify({type: "MANAGER_DEVICE_PAIRING", pairKey: "x"})), null);
    assert.equal(parseActivationQr(JSON.stringify({
        type: "MANAGER_DEVICE_ACTIVATION",
        serverUrl: "https://manager.example.com/v1/api",
        activationCode: "ABC",
    })), null);
});

test("normalizes manually typed activation codes", () => {
    assert.equal(normalizeActivationCode("ab cd-ef gh"), "ABCDEFGH");
    assert.equal(formatActivationCode("abcdefgh"), "ABCD-EFGH");
    assert.equal(formatActivationCode("abc"), "ABC");
    assert.equal(isActivationCodeComplete("ABCD-EFGH"), true);
    assert.equal(isActivationCodeComplete("ABCD-EFG"), false);
});

test("recognizes faults that require a new operator login or a new activation", () => {
    assert.equal(isOperatorSessionFault("No operator signed in on device"), true);
    assert.equal(isDeviceCredentialFault("Invalid device pair key"), true);
    assert.equal(isDeviceCredentialFault("Invalid device credentials"), true);
    assert.equal(isDeviceCredentialFault("Shipment not found"), false);
});
